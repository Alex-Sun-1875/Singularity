"""Bake approved option C into existing fire textures, preserving every alpha byte.

One palette also generates the fire-only shield ramp, jet wash and particle colours.
Existing geometry, clocks, pooling, texture dimensions and shader sample counts stay.
"""
from pathlib import Path
import argparse
import hashlib
import json
import re
import uuid
import numpy as np
from PIL import Image

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
COCOS = ROOT / 'src/cocos'
PRODUCTION = COCOS / 'assets/resources/vfx/production'
ORIGINALS, CANDIDATES = HERE / 'originals', HERE / 'assets'
ORIGINALS.mkdir(exist_ok=True)
CANDIDATES.mkdir(exist_ok=True)
args = argparse.ArgumentParser()
args.add_argument('--sample', action='store_true')
args.add_argument('--install', action='store_true')
options = args.parse_args()
proposal = json.loads((HERE.parent / 'fire-family-colour-options-v39/provenance.json').read_text(encoding='utf-8'))
profile = next(p for p in proposal['profiles'] if p['id'] == 'C')
roles = dict(zip(['shadow', 'low', 'body', 'highlight', 'core'], profile['stops']))
config = {'id': 'amber-gold-v40', 'selection': 'C', 'userSelected': '2026-11-17', 'colours': roles,
          'rankKnots': [0, .20, .90, .985, 1], 'alphaPolicy': 'preserve all source alpha bytes',
          'source': 'source-art/skills/fire-family-colour-options-v39/provenance.json'}
(HERE / 'palette.json').write_text(json.dumps(config, ensure_ascii=False, indent=2)+'\n', encoding='utf-8')
palette = np.array([[int(h[i:i+2], 16) for i in (1, 3, 5)] for h in profile['stops']], dtype=float)
names = ['fire-ground-jets-v27', 'fire-lance-v30', 'fire-field-flow-v30', 'fire-meteor-reference-tail-v33',
         'fire-contact-fan-v30', 'fire-meteor-burst-v32', 'fire-jet-seal-v27',
         'fire-meteor-seal-colour-v37', 'fire-meteor-seal-light-v37', 'fire-tongues-v1']
if options.sample:
    names = names[:3]
sha = lambda p: hashlib.sha256(p.read_bytes()).hexdigest()
records = []
for name in names:
    production = PRODUCTION / (name+'.png')
    source = ORIGINALS / production.name
    if not source.exists():
        source.write_bytes(production.read_bytes())
    raw = np.asarray(Image.open(source).convert('RGBA'))
    colour = raw[..., :3].astype(float)
    opacity = raw[..., 3].astype(float)/255
    peak = colour.max(axis=2)/255
    light = name.endswith('-light-v37')
    weights = peak if light else opacity**.7
    luminance = colour @ np.array([.2126, .7152, .0722])
    bins = np.clip(np.round(luminance*16), 0, 4095).astype(int)
    histogram = np.bincount(bins.ravel(), weights=weights.ravel(), minlength=4096)
    rank = (np.cumsum(histogram)-histogram*.5)/max(histogram.sum(), 1)
    heat = rank[bins]
    graded = np.stack([np.interp(heat, config['rankKnots'], palette[:, c]) for c in range(3)], axis=-1)
    # Preserve the encoded light intensity, particularly the additive seal halo.
    graded *= peak[..., None]
    result = raw.copy()
    active = peak > 0 if light else opacity > 0
    result[..., :3][active] = np.round(np.clip(graded[active], 0, 255)).astype(np.uint8)
    if not np.array_equal(result[..., 3], raw[..., 3]):
        raise RuntimeError('Alpha changed: '+name)
    target = CANDIDATES / production.name
    Image.fromarray(result).save(target, optimize=True)
    if options.install:
        if (COCOS / 'temp/taptap-build.lock').exists():
            raise RuntimeError('Another build is using the project; keep candidates and retry installation later.')
        if sha(production) not in [sha(source), sha(target)]:
            raise RuntimeError('Production texture changed independently: '+name)
        production.write_bytes(target.read_bytes())
    records.append({'name': name, 'sourceSha256': sha(source), 'resultSha256': sha(target),
                    'pixels': [raw.shape[1], raw.shape[0]], 'alphaExactlyPreserved': True, 'additiveLight': light})

def vec(role):
    return 'vec3('+', '.join(f'{x/255:.8f}' for x in palette[list(roles).index(role)])+')'

def update_text(relative, transform):
    file = COCOS / relative
    backup = ORIGINALS / file.name
    if not backup.exists():
        backup.write_bytes(file.read_bytes())
    text = file.read_text(encoding='utf-8')
    changed = transform(text)
    newline = '\r\n' if b'\r\n' in backup.read_bytes() else '\n'
    encoded = changed.replace('\r\n', '\n').replace('\n', newline).encode('utf-8')
    if file.read_bytes() != encoded:
        file.write_bytes(encoded)

if options.install:
    module = COCOS / 'assets/scripts/shared/assets/FirePalette.ts'
    module.write_text('/** Approved option C; generated by source-art/skills/fire-family-amber-v40/install_palette.py. */\n'
                      'export const FIRE_PALETTE = Object.freeze('+json.dumps({'id': config['id'], **roles}, ensure_ascii=False, separators=(',', ':'))+' as const);\n', encoding='utf-8')
    meta = Path(str(module)+'.meta')
    if not meta.exists():
        meta.write_text(json.dumps({'ver': '4.0.24', 'importer': 'typescript', 'imported': True, 'uuid': str(uuid.uuid4()), 'files': [], 'subMetas': {}, 'userData': {}}, separators=(',', ':'))+'\n', encoding='utf-8')
    def import_palette(text, path):
        line = "import {FIRE_PALETTE} from '"+path+"';\n"
        return text if line in text else line+text
    update_text('assets/scripts/features/combat/runtime/NativeSkillVfx.ts', lambda t: import_palette(t, '../../../shared/assets/FirePalette').replace("FIRE='#fa913d'", 'FIRE=FIRE_PALETTE.body').replace("this.stroke(l,r,'#ffc473'", 'this.stroke(l,r,FIRE_PALETTE.highlight'))
    update_text('assets/scripts/features/combat/runtime/UnifiedShieldEffects.ts', lambda t: import_palette(t, '../../../shared/assets/FirePalette').replace("FIR:{tint:'#ff9746'", 'FIR:{tint:FIRE_PALETTE.body'))
    def particles(text):
        text = import_palette(text, './FirePalette')
        for name, start, end in [('flame', 'body', 'shadow'), ('ember', 'highlight', 'low'), ('fireCore', 'core', 'body')]:
            def replace(match):
                line = re.sub(r"color:'[^']*'", 'color:FIRE_PALETTE.'+start, match.group())
                return re.sub(r"end:'[^']*'", 'end:FIRE_PALETTE.'+end, line)
            text = re.sub(r'(?m)^ '+name+r':\{[^\n]+', replace, text)
        return text
    update_text('assets/scripts/shared/assets/VfxAssets.ts', particles)
    def ground(text):
        text = re.sub(r'(?m)^      vec3 fill = mix\([^\n]+', '      vec3 fill = mix('+vec('low')+', '+vec('body')+', (1.0-radius)*0.7+flow*0.3);', text)
        text = re.sub(r'(?m)^      color = \(glyph\.rgb \* mix\([^\n]+', '      color = (glyph.rgb*glyph.a + fill*fillAlpha*(1.0-glyph.a))/max(alpha, 0.0001);', text)
        text = text.replace('Original measured flame low/mid colours, with a light translucent', 'Approved shared amber low/body colours, with a light translucent')
        text = text.replace('      // Small per-channel residual measured on the actual native front ring,\n      // after its reference-derived matte passes through mesh resampling.\n', '      // The recoloured glyph and the fill use the same palette; no legacy\n      // per-channel yellow correction is applied after recolouring.\n')
        return text
    update_text('assets/resources/vfx/production/fire-ground-v27.effect', ground)
    def shield(text):
        if 'fireFamilyColour' in text:
            return text
        function = '\n  // Generated from the same approved C palette as the fire flipbooks.\n  vec3 fireFamilyColour(float heat) {\n'
        for index, (lo, hi) in enumerate(zip(config['rankKnots'][:-1], config['rankKnots'][1:])):
            function += '    '+('if (heat < '+f'{hi:.3f}'+') ' if index < 3 else '')+'return mix('+vec(list(roles)[index])+', '+vec(list(roles)[index+1])+', clamp((heat-'+f'{lo:.3f}'+')/'+f'{hi-lo:.3f}'+', 0.0, 1.0));\n'
        function += '  }\n'
        text = text.replace('  vec4 frag () {', function+'  vec4 frag () {')
        marker = '    vec3 tint = SRGBToLinear(shieldTint.rgb)'
        branch = '    // Fire uses display RGB like the other unlit fire passes. Keep the\n    // existing alpha, depth and standard colour path for the other families.\n    if (motifChannel.b > 0.5) {\n      float heat = clamp(0.60 + rim*0.45 + glyph*0.38*shieldState.z + ripple*0.20, 0.0, 1.0);\n      return vec4(fireFamilyColour(heat), min(alpha, 0.80));\n    }\n'
        if marker not in text:
            raise RuntimeError('Shield shader anchor changed')
        return text.replace(marker, branch+marker)
    update_text('assets/resources/vfx/production/shield-unified-v1.effect', shield)

record = {'selection': 'C', 'palette': config, 'installed': options.install, 'sampleOnly': options.sample,
          'newGeneration': False, 'method': 'deterministic RGB remapping; original alpha retained',
          'textures': records, 'artStatus': 'selected palette; native integration verification recorded separately'}
(HERE / ('sample-provenance.json' if options.sample else 'provenance.json')).write_text(json.dumps(record, ensure_ascii=False, indent=2)+'\n', encoding='utf-8')
print(json.dumps({'selection': 'C', 'textures': len(records), 'alphaBytesPreserved': True, 'installed': options.install}, ensure_ascii=False))
