function Start()
    local Environment=require("Game.Environment")
    local scene=Scene()
    scene:CreateComponent("Octree")
    local environment=Environment.New(scene,"road")
    assert(environment.root and environment.root:GetNumChildren()>80,"environment must contain real scene geometry")
    local p=Environment.ToWorld(800,450)
    assert(math.abs(p.x)<0.001 and math.abs(p.z)<0.001)
    local x,y=Environment.ToChapter(p)
    assert(math.abs(x-800)<0.001 and math.abs(y-450)<0.001)
    assert(environment.root:GetChild("Ground"),"terrain mesh required")
    assert(environment.root:GetChild("Road"),"road mesh required")
    print("[EnvironmentTest] PASS 3D terrain, road, environment geometry and coordinate roundtrip")
end
