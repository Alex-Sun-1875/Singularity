"""Prove which imported GLB textures can replace duplicate runtime PNG loads.

Only exact decoded RGBA matches with equal wrap/filter settings are eligible.
The generated UUID allowlist is used only by the freshly prepared TapTap build.
Source images, model geometry and importer metadata remain unchanged.
"""
import hashlib
import io
import json
import struct
from pathlib import Path
from PIL import Image

PROJECT = Path(__file__).resolve().parents[1]
ROOT = PROJECT / 'assets/resources'


def rgba_hash(data):
    with Image.open(io.BytesIO(data)) as image:
        rgba = image.convert('RGBA')
        return hashlib.sha256(struct.pack('<II', *rgba.size) + rgba.tobytes()).hexdigest()


def read(path):
    return json.loads(path.read_text(encoding='utf-8-sig'))


def prepare():
    manifest = read(ROOT / 'actors/raphael/manifest.json')
    # Follow the actual shipping prefab, so older comparison models cannot
    # silently contribute stale or unrelated texture matches.
    model = ROOT / 'actors/raphael' / (manifest['prefabRoot'] + '.glb')
    raw = model.read_bytes()
    if raw[:4] != b'glTF' or struct.unpack_from('<I', raw, 4)[0] != 2:
        raise ValueError('Expected glTF 2.0: ' + str(model))
    json_length, json_type = struct.unpack_from('<II', raw, 12)
    if json_type != 0x4E4F534A:
        raise ValueError('Missing glTF JSON chunk')
    gltf = json.loads(raw[20:20 + json_length])
    bin_length, bin_type = struct.unpack_from('<II', raw, 20 + json_length)
    if bin_type != 0x004E4942:
        raise ValueError('Missing glTF binary chunk')
    blob = raw[28 + json_length:28 + json_length + bin_length]
    meta = read(model.with_name(model.name + '.meta'))
    paths = sorted({path for record in manifest['materials'] for path in record['maps'].values()})
    candidates = {}
    for path in paths:
        file = (model.parent / path).resolve()
        if not file.is_relative_to(ROOT.resolve()):
            raise ValueError('Texture path outside resources: ' + path)
        texture_meta = read(file.with_name(file.name + '.meta'))
        sampler = next(s['userData'] for s in texture_meta['subMetas'].values() if s['importer'] == 'texture')
        candidates.setdefault(rgba_hash(file.read_bytes()), []).append((file.relative_to(ROOT).as_posix().rsplit('.', 1)[0] + '/texture', sampler))
    image_hashes = {}
    image_indices = {}
    for sub in meta['subMetas'].values():
        if sub['importer'] != 'gltf-embeded-image':
            continue
        image_index = sub['userData']['gltfIndex']
        image = gltf['images'][image_index]
        image_indices[sub['uuid']] = image_index
        if 'bufferView' not in image:
            continue
        view = gltf['bufferViews'][image['bufferView']]
        offset = view.get('byteOffset', 0)
        image_hashes[sub['uuid']] = rgba_hash(blob[offset:offset + view['byteLength']])
    reuse = {}
    referenced = set()
    def references(value):
        if isinstance(value, dict):
            for key, item in value.items():
                if key.endswith('Texture') and isinstance(item, dict) and 'index' in item:
                    referenced.add(item['index'])
                else:
                    references(item)
        elif isinstance(value, list):
            for item in value:
                references(item)
    references(gltf.get('materials', []))
    referenced_images = {gltf['textures'][index]['source'] for index in referenced
                         if 'source' in gltf['textures'][index]}
    sampler_keys = ['wrapModeS', 'wrapModeT', 'minfilter', 'magfilter', 'mipfilter']
    for sub in meta['subMetas'].values():
        if sub['importer'] != 'texture':
            continue
        sampler = sub['userData']
        if image_indices.get(sampler.get('imageUuidOrDatabaseUri')) not in referenced_images:
            continue
        digest = image_hashes.get(sampler.get('imageUuidOrDatabaseUri'))
        matches = [(path, target) for path, target in candidates.get(digest, [])
                   if all(sampler.get(key) == target.get(key) for key in sampler_keys)]
        if matches:
            reuse[sub['uuid']] = {'paths': [path for path, _ in matches], 'anisotropy': matches[0][1].get('anisotropy', 0)}
    output = PROJECT / 'assets/scripts/shared/assets/NativeTextureReuse.ts'
    content = ('/** Generated by tools/prepare-native-texture-reuse.py; exact RGBA + sampler matches. */\n'
               'export const NATIVE_TEXTURE_REUSE:Readonly<Record<string,{paths:readonly string[];anisotropy:number}>> = '
               + json.dumps(reuse, ensure_ascii=False, indent=2) + ';\n')
    if not output.exists() or output.read_text(encoding='utf-8') != content:
        output.write_text(content, encoding='utf-8')
    print('Verified native texture reuse:', len(reuse), 'imported textures')


if __name__ == '__main__':
    prepare()
