// Build-time policy only. Runtime code never reads a URL, storage value or global switch.
const fs=require('node:fs'),path=require('node:path'),{createHash}=require('node:crypto');
const names=['dev','test','release'];
function profileFor(name='test'){
 if(!names.includes(name))throw new Error('Build profile must be dev, test or release.');
 const rules={noSkillCooldown:name==='dev',monsterExperienceMultiplier:name==='dev'?5:1,
  guaranteedBossHighTierLoot:name==='dev',developmentTools:name==='dev',unlimitedDailyExperience:name==='dev',storagePrefix:name==='dev'?'singularity.dev.':''};
 const digest=createHash('sha256').update(JSON.stringify(rules)).digest('hex').slice(0,12);
 return {schemaVersion:2,name,marker:`singularity-build-profile-v2-${name}-${digest}`,...rules};
}
function runtimeSource(name){return '/** Generated by tools/taptap-config.cjs; do not edit. */\n'+
 'export interface BuildProfile {readonly schemaVersion:number;readonly name:"dev"|"test"|"release";readonly marker:string;readonly noSkillCooldown:boolean;readonly monsterExperienceMultiplier:number;readonly guaranteedBossHighTierLoot:boolean;readonly developmentTools:boolean;readonly unlimitedDailyExperience:boolean;readonly storagePrefix:string}\n'+
 'export const BUILD_PROFILE:Readonly<BuildProfile> = Object.freeze('+JSON.stringify(profileFor(name))+');\n';}
function verifyBuild(directory,name){
 const expected=profileFor(name),seen=new Set();
 function walk(dir){for(const entry of fs.readdirSync(dir,{withFileTypes:true})){
  if(entry.isSymbolicLink())throw new Error('Build profile verification does not follow links: '+entry.name);
  const file=path.join(dir,entry.name);
  if(entry.isDirectory())walk(file);
  else if(entry.name.endsWith('.js'))for(const marker of fs.readFileSync(file,'utf8').match(/singularity-build-profile-v\d+-(?:dev|test|release)(?:-[a-f0-9]{12})?/g)||[])seen.add(marker);
 }}
 walk(directory);
 if(seen.size!==1||!seen.has(expected.marker))throw new Error('Compiled gameplay profile does not match '+name+'; rebuild Cocos instead of relabeling an old export. Found: '+[...seen].join(', '));
 return expected;
}
module.exports={profileFor,runtimeSource,verifyBuild};
if(require.main===module){try{const args=process.argv.slice(2),get=flag=>args[args.indexOf(flag)+1];console.log(JSON.stringify(args.includes('--verify-build')?verifyBuild(get('--verify-build'),get('--profile')||'test'):profileFor(get('--profile')||'test')));}catch(error){console.error(error.message);process.exitCode=1;}}
