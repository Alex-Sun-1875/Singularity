// Package the source-verified CPU module beside Cocos' own WASM assets. No
// compiler/download runs during game builds; rebuild explicitly when editing Rust.
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const project=path.resolve(__dirname,'..'),directory=path.join(__dirname,'navigation-wasm');
const binary=path.join(directory,'navigation.wasm'),manifest=JSON.parse(fs.readFileSync(path.join(directory,'navigation.json'),'utf8'));
const hash=data=>crypto.createHash('sha256').update(data).digest('hex');
const bytes=fs.readFileSync(binary);
if(manifest.abi!==3||manifest.sourceSha256!==hash(fs.readFileSync(path.join(directory,'navigation.rs')))||manifest.sha256!==hash(bytes)||manifest.bytes!==bytes.length||!bytes.subarray(0,8).equals(Buffer.from([0,97,115,109,1,0,0,0])))throw Error('Stale/invalid navigation WASM. Run tools/navigation-wasm/Build-NavigationWasm.ps1.');
const relative='cocos-js/assets/navigation-search-'+manifest.sha256.slice(0,12)+'.wasm';
const profile=JSON.parse(fs.readFileSync(path.join(project,'release/taptap.json'),'utf8'));
// The module stays packaged when default-off, so one immutable build supports
// runtime A/B comparisons. Cocos' package policy still controls availability.
if(typeof profile.computationWasm!=='boolean')throw Error('release/taptap.json.computationWasm must be true or false.');
const available=profile.engineWasmSubpackage!==false;
const enabled=profile.computationWasm!==false&&available;
const args=process.argv.slice(2),at=args.indexOf('--build');
if(args.includes('--prepare')){
 const config={enabled,available,abi:3,path:relative,subpackage:'__ccWasmAssetSubpkg__',sha256:manifest.sha256,bytes:manifest.bytes};
 const file=path.join(project,'assets/scripts/features/navigation/runtime/NavigationWasmConfig.ts');
 const text='// Generated by tools/prepare-navigation-wasm.cjs from the verified binary.\nexport const NAVIGATION_WASM='+JSON.stringify(config)+' as const;\n';
 if(!fs.existsSync(file)||fs.readFileSync(file,'utf8')!==text)fs.writeFileSync(file,text);
}
if(at>=0){
 const build=path.resolve(args[at+1]),folder=path.join(build,'cocos-js/assets');
 const gameJson=path.join(build,'game.json');
 if(available&&fs.existsSync(gameJson)){
  const game=JSON.parse(fs.readFileSync(gameJson,'utf8')),pack=(game.subPackages||game.subpackages)?.find(p=>p.name==='__ccWasmAssetSubpkg__');
  if(!pack||pack.root.replace(/\\/g,'/').replace(/\/$/,'')!=='cocos-js/assets')throw Error('Navigation WASM requires the existing Cocos WASM asset subpackage.');
 }
 fs.mkdirSync(folder,{recursive:true});
 // Only stale, generated versions of our own module inside this build output.
 for(const name of fs.readdirSync(folder))if(/^navigation-search-[0-9a-f]{12}\.wasm$/.test(name)&&(!available||name!==path.basename(relative)))fs.unlinkSync(path.join(folder,name));
 if(available)fs.copyFileSync(binary,path.join(build,relative));
}
console.log(JSON.stringify({navigationWasm:relative,enabled,available,bytes:bytes.length,sha256:manifest.sha256}));
