"""Bake existing HUD art; no generated artwork or runtime canvas dependency.

The icon alpha follows Creator 3.8.8's 64-segment ellipse, in the same
fractional frame rectangle as UiSkin.hudSkillFrame. RGB and resolution stay
unchanged. The common button face flattens its three existing static layers.
Run from any directory with the project's existing Pillow installation.
"""
from pathlib import Path
import hashlib
import json
import math
import re
import uuid

from PIL import Image, ImageChops, ImageDraw

PROJECT = Path(__file__).resolve().parents[1]
UI = PROJECT / 'assets/resources/ui'
SOURCE = UI / 'combat-relief'
OUTPUT = SOURCE / 'hud-circular'
SKIN = UI / 'quiet-bronze'
NAMESPACE = uuid.UUID('da083e9d-c263-48c6-9047-5113c929e94f')


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def meta(path):
    """Stable Creator UUIDs; keep subsequent editor import metadata intact."""
    target = Path(str(path) + '.meta')
    if target.exists():
        return
    identifier = str(uuid.uuid5(NAMESPACE, path.relative_to(PROJECT).as_posix()))
    data = dict(ver='1.2.0', importer='directory', imported=True,
                uuid=identifier, files=[], subMetas={}, userData={})
    if path.suffix == '.png':
        data.update(ver='1.0.27', importer='image', files=['.json', '.png'],
                    userData=dict(type='texture', fixAlphaTransparencyArtifacts=False,
                                  hasAlpha=True, redirect=identifier + '@6c48a'))
        data['subMetas']['6c48a'] = dict(
            ver='1.0.22', importer='texture', imported=True,
            uuid=identifier + '@6c48a', displayName=path.stem, id='6c48a',
            name='texture', files=['.json'], subMetas={}, userData=dict(
                wrapModeS='clamp-to-edge', wrapModeT='clamp-to-edge',
                minfilter='linear', magfilter='linear', mipfilter='none',
                anisotropy=0, isUuid=True, imageUuidOrDatabaseUri=identifier,
                visible=False))
    elif path.suffix == '.ts':
        data.update(ver='4.0.24', importer='typescript')
    elif path.is_file():
        data.update(ver='2.0.1', importer='json', files=['.json'])
    target.write_text(json.dumps(data, indent=2) + '\n', encoding='utf-8')


def circle_alpha(image, inset=0):
    width, height = image.size
    sampling = 4
    alpha = Image.new('L', (width * sampling, height * sampling))
    rx, ry = width / 2 - inset, height / 2 - inset
    points = [((width / 2 + rx * math.cos(i * math.tau / 64)) * sampling,
               (height / 2 + ry * math.sin(i * math.tau / 64)) * sampling)
              for i in range(64)]
    ImageDraw.Draw(alpha).polygon(points, fill=255)
    alpha = alpha.resize(image.size, Image.Resampling.BOX)
    result = image.copy()
    result.putalpha(ImageChops.multiply(image.getchannel('A'), alpha))
    return result


def icon_atlases():
    """Pack default HUD loadouts at original resolution; alternatives stay available."""
    catalog = (PROJECT / 'assets/scripts/features/combat/runtime/CombatSkillIcons.ts').read_text(encoding='utf-8')
    icons = dict(re.findall(r"([A-Z]+_\w+):'([^']+)'", catalog))
    loadouts = (PROJECT / 'assets/scripts/features/progression/common/CombatLoadouts.ts').read_text(encoding='utf-8')
    groups = re.findall(r"^ (WAR|BOW|FIR|THU):\{[^\n]*activeSlots:\[([^\]]+)\],ultimate:'([^']+)'", loadouts, re.M)
    assert len(groups) == 4
    output = OUTPUT / 'atlases'
    output.mkdir(exist_ok=True)
    meta(output)
    manifest, entries = {}, []
    for group, slots, ultimate in groups:
        attack = 'attack' if group == 'WAR' else 'bow' if group == 'BOW' else 'staff'
        names = [attack, icons['COM_01']] + [icons[name] for name in re.findall(r"'([^']+)'", slots)] + [icons[ultimate]]
        assert len(names) == 7 and len(set(names)) == 7
        atlas = Image.new('RGBA', (1024, 512))
        for index, name in enumerate(names):
            source = OUTPUT / (name + '.png')
            image = Image.open(source).convert('RGBA')
            assert image.size == (256, 256)
            x, y = index % 4 * 256, index // 4 * 256
            atlas.paste(image, (x, y))  # Copy every RGBA value, including transparent RGB.
            assert atlas.crop((x, y, x + 256, y + 256)).tobytes() == image.tobytes()
        target = output / (group.lower() + '.png')
        atlas.save(target, optimize=True)
        meta(target)
        manifest[group] = names
        entries.append(dict(group=group, output=target.relative_to(UI).as_posix(),
                            size=atlas.size, outputSha256=digest(target),
                            sources=[dict(name=name, sha256=digest(OUTPUT / (name + '.png'))) for name in names]))
    typescript = PROJECT / 'assets/scripts/shared/ui/HudSkillAtlas.ts'
    typescript.write_text(
        '// Generated by tools/build-hud-render-assets.py; original 256px RGBA tiles, four columns.\n'
        '// Other equipped skills use their original circular image.\n'
        'export const HUD_SKILL_ATLAS_ICONS:Readonly<Record<string,readonly string[]>>=' +
        json.dumps(manifest, indent=1) + ';\n', encoding='utf-8')
    meta(typescript)
    provenance = output / 'provenance.json'
    provenance.write_text(json.dumps(dict(
        recipe='src/cocos/tools/build-hud-render-assets.py',
        method='Lossless 1:1 tile packing; no resize, trimming, rotation or generated pixels',
        visualAcceptance='See docs/performance/continuous-spawn-cpu-20261114.md; generation alone is not acceptance',
        entries=entries), indent=2) + '\n', encoding='utf-8')
    meta(provenance)


def panel_atlas():
    """Original UI pixels with clamp-equivalent two-pixel edge extrusion."""
    # The 512px track spans the texture width, retaining its original horizontal
    # CLAMP_TO_EDGE behavior. The other rectangles have padding on all sides.
    regions = {
        'leather-inset-v8': (2, 2, 256, 256),
        'unified-gold-panel-v13': (2, 262, 256, 128),
        'bar-track': (0, 394, 512, 32),
        'bar-health-fill': (2, 430, 488, 12),
        'bar-focus-fill': (2, 446, 488, 12),
        'bar-cap-left': (262, 2, 24, 32),
        'bar-cap-right': (290, 2, 24, 32),
    }
    atlas = Image.new('RGBA', (512, 512))
    entries = []
    for name, (x, y, width, height) in regions.items():
        source = SKIN / (name + '.png')
        image = Image.open(source).convert('RGBA')
        assert image.size == (width, height)
        for dy in range(-2, height + 2):
            row = image.crop((0, max(0, min(height - 1, dy)), width,
                              max(0, min(height - 1, dy)) + 1))
            atlas.paste(row, (x, y + dy))
            if x:
                atlas.paste(row.crop((0, 0, 1, 1)).resize((2, 1)), (x - 2, y + dy))
            if x + width < atlas.width:
                atlas.paste(row.crop((width - 1, 0, width, 1)).resize((2, 1)),
                            (x + width, y + dy))
        entries.append(dict(source=source.relative_to(UI).as_posix(), rect=[x, y, width, height],
                            sha256=digest(source), rgbaUnchanged=True))
    for name, (x, y, width, height) in regions.items():
        assert atlas.crop((x, y, x + width, y + height)).tobytes() == Image.open(SKIN / (name + '.png')).convert('RGBA').tobytes()
    output = SKIN / 'hud-panel-atlas-v1.png'
    atlas.save(output, optimize=True)
    meta(output)
    manifest = SKIN / 'hud-panel-atlas-v1.provenance.json'
    manifest.write_text(json.dumps(dict(
        recipe='src/cocos/tools/build-hud-render-assets.py',
        method='Lossless original RGBA tiles, two-pixel edge extrusion, no mipmaps or image resampling',
        output=output.relative_to(UI).as_posix(), size=atlas.size,
        outputSha256=digest(output), entries=entries,
        visualAcceptance='See docs/performance/continuous-spawn-cpu-20261114.md; generation alone is not acceptance'),
        indent=2) + '\n', encoding='utf-8')
    meta(manifest)
    typescript = PROJECT / 'assets/scripts/shared/ui/HudPanelAtlas.ts'
    typescript.write_text(
        '// Generated by tools/build-hud-render-assets.py; original pixels and sampling borders.\n'
        "export const HUD_PANEL_ATLAS_PATH='ui/quiet-bronze/hud-panel-atlas-v1';\n"
        'export const HUD_PANEL_ATLAS_REGIONS:Readonly<Record<string,readonly [number,number,number,number]>>=' +
        json.dumps({'ui/quiet-bronze/' + name: rect for name, rect in regions.items()}, indent=1) + ';\n',
        encoding='utf-8')
    meta(typescript)


def frame_pair_atlases():
    """Shared frame pairs at original RGBA size, retaining native nine-slicing."""
    paths, regions = {}, {}
    for shape, height, names in [
        ('panel', 512, ['double-gold-inset-v6', 'double-gold-frame-v6', 'double-gold-frame-rpg-v4']),
        ('capsule', 128, ['menu-pill-inset-v5', 'menu-pill-frame-v5']),
    ]:
        atlas = Image.new('RGBA', (516 * len(names), height + 4))
        entries = []
        for column, name in enumerate(names):
            source = SKIN / (name + '.png')
            tile = Image.open(source).convert('RGBA')
            assert tile.size == (512, height)
            x, y = 2 + column * 516, 2
            for dy in range(-2, height + 2):
                sy = max(0, min(height - 1, dy))
                row = tile.crop((0, sy, 512, sy + 1))
                atlas.paste(row, (x, y + dy))
                atlas.paste(row.crop((0, 0, 1, 1)).resize((2, 1), Image.Resampling.NEAREST), (x - 2, y + dy))
                atlas.paste(row.crop((511, 0, 512, 1)).resize((2, 1), Image.Resampling.NEAREST), (x + 512, y + dy))
            assert atlas.crop((x, y, x + 512, y + height)).tobytes() == tile.tobytes()
            key = 'ui/quiet-bronze/' + name
            paths[key] = 'ui/quiet-bronze/gold-frame-' + shape + '-atlas-v1'
            regions[key] = [x, y, 512, height]
            entries.append(dict(source=source.relative_to(UI).as_posix(), rect=regions[key],
                                sha256=digest(source), rgbaUnchanged=True))
        output = SKIN / ('gold-frame-' + shape + '-atlas-v1.png')
        atlas.save(output, optimize=True)
        meta(output)
        manifest = output.with_suffix('.provenance.json')
        manifest.write_text(json.dumps(dict(
            recipe='src/cocos/tools/build-hud-render-assets.py',
            method='Lossless RGBA tiles with two-pixel clamp-equivalent edge extrusion; no resampling or mipmaps',
            output=output.relative_to(UI).as_posix(), size=list(atlas.size),
            outputSha256=digest(output), entries=entries,
            visualAcceptance='See docs/performance/native-batching-20261114.md; generation alone is not acceptance'),
            indent=2) + '\n', encoding='utf-8')
        meta(manifest)
    typescript = PROJECT / 'assets/scripts/shared/ui/GoldFrameAtlas.ts'
    typescript.write_text(
        '// Generated by tools/build-hud-render-assets.py; original frame pixels and sampling borders.\n'
        'export const GOLD_FRAME_ATLAS_PATHS:Readonly<Record<string,string>>=' + json.dumps(paths, indent=1) + ';\n'
        'export const GOLD_FRAME_ATLAS_REGIONS:Readonly<Record<string,readonly [number,number,number,number]>>=' +
        json.dumps(regions, indent=1) + ';\n', encoding='utf-8')
    meta(typescript)


def main():
    OUTPUT.mkdir(exist_ok=True)
    meta(OUTPUT)
    icons = (PROJECT / 'assets/scripts/features/combat/runtime/CombatSkillIcons.ts').read_text(encoding='utf-8')
    names = sorted(set(re.findall(r":'(rpg-[^']+)'", icons)) | {'attack', 'bow', 'staff', 'dash'})
    entries = []
    for name in names:
        source, output = SOURCE / (name + '.png'), OUTPUT / (name + '.png')
        image = Image.open(source).convert('RGBA')
        inset = min(image.size) * .047 if name.startswith('rpg-') else 0
        result = circle_alpha(image, inset)
        assert result.convert('RGB').tobytes() == image.convert('RGB').tobytes()
        result.save(output, optimize=True)
        meta(output)
        entries.append(dict(source=source.relative_to(UI).as_posix(),
                            output=output.relative_to(UI).as_posix(), size=image.size,
                            inset=inset, rgbUnchanged=True,
                            sourceSha256=digest(source), outputSha256=digest(output)))
    source = SKIN / 'mask-cooldown.png'
    output = OUTPUT / 'cooldown.png'
    circle_alpha(Image.open(source).convert('RGBA')).save(output, optimize=True)
    meta(output)
    entries.append(dict(source=source.relative_to(UI).as_posix(),
                        output=output.relative_to(UI).as_posix(),
                        sourceSha256=digest(source), outputSha256=digest(output)))

    # 1024 preserves at least the original 512px bezel sampling density.
    # The outer quad remains exactly 1.6 times the existing button diameter.
    face = Image.new('RGBA', (1024, 1024))
    layers = [('skill-soft-shadow-v17', 1.6), ('skill-soft-halo-v17', 1.36),
              ('unified-gold-skill-v18', 1)]
    for name, ratio in layers:
        size = round(1024 * ratio / 1.6)
        layer = Image.open(SKIN / (name + '.png')).convert('RGBA')
        layer = layer.resize((size, size), Image.Resampling.LANCZOS)
        offset = (1024 - size) // 2
        face.alpha_composite(layer, (offset, offset))
    output = SKIN / 'hud-skill-face-v19.png'
    face.save(output, optimize=True)
    meta(output)
    entries.append(dict(output=output.relative_to(UI).as_posix(), size=face.size,
                        layers=[dict(source=name + '.png', diameterRatio=ratio,
                                     sourceSha256=digest(SKIN / (name + '.png')))
                                for name, ratio in layers], outputSha256=digest(output)))
    manifest = OUTPUT / 'provenance.json'
    manifest.write_text(json.dumps(dict(
        recipe='src/cocos/tools/build-hud-render-assets.py',
        method='Pillow deterministic alpha clipping and static layer composition; original artwork retained',
        mask='Creator 3.8.8 Mask.GRAPHICS_ELLIPSE, 64 segments, 4x coverage',
        visualAcceptance='See docs/performance/performance-regression.md; generation is not visual acceptance',
        entries=entries), ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    meta(manifest)
    icon_atlases()
    panel_atlas()
    frame_pair_atlases()
    print(f'Baked {len(names)} circular icons, cooldown alpha and one common face.')


if __name__ == '__main__':
    main()
