"""Deterministic alpha cleanup of the retained cloud-generated sword ribbon.

This does not synthesize replacement art. It preserves the generated silver and
gold striations while suppressing the broad low-value grey smoke from the source.
"""
from pathlib import Path
import hashlib
import json
import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "source-art/skills/pure-skills-v2/melee-material-v3"
OUTPUT = ROOT / "src/cocos/assets/resources/vfx/production/melee-material-v3"
OUTPUT.mkdir(parents=True, exist_ok=True)

im = Image.open(SOURCE / "generated-strip.png").convert("RGBA")
# The raw generated image has stray alpha=1 pixels outside the ribbon. Explicit
# signal bounds preserve all visible silver/gold material without a huge canvas.
crop = (24, 246, 2130, 448)
pixels = np.asarray(im.crop(crop)).astype(np.float32)
rgb = pixels[..., :3]
luma = rgb[..., 0] * .2126 + rgb[..., 1] * .7152 + rgb[..., 2] * .0722
mask = np.clip((luma - 104) / 126, 0, 1) ** .82
pixels[..., 3] *= mask
# Retained striations must emit silver/gold rather than paint grey over a lit
# ground. Normalize their RGB exposure while keeping colour ratios and the
# existing alpha mask: transparent gaps and faint wisps remain transparent.
exposed = np.minimum(255, rgb * 1.08 + 9)
peak = np.maximum(1, exposed.max(axis=2))
pixels[..., :3] = exposed * ((230 + 25 * mask) / peak)[..., None]
pixels[pixels[..., 3] < 1, 3] = 0
image = Image.fromarray(np.uint8(np.clip(pixels, 0, 255)), "RGBA")
image = image.resize((1536, 192), Image.Resampling.LANCZOS)
image.save(OUTPUT / "steel-ribbon.png")

provenance = {
    "generation": "OpenAI built-in cloud image_gen; generated by root agent",
    "generatedSource": "generated-strip.png",
    "generatedSourceSha256": hashlib.sha256((SOURCE / "generated-strip.png").read_bytes()).hexdigest(),
    "reference": "steel-reference.png; material crop of evolution-war.png, close-range selected direction",
    "sourceSize": list(im.size),
    "derive": {"script": "tools/make-melee-material-v3.py", "crop": list(crop),
               "luminanceAlpha": "source_alpha * clamp((luminance - 104) / 126,0,1)^0.82",
               "rgbExposure": "preserve ratio of min(255, source_rgb*1.08+9), normalize RGB peak to 230+25*alpha-mask", "size": [1536,192],
               "preserved": "generated silver/gold striations and semitransparent alpha"},
    "runtime": "native curved transparent sword mesh; no new projectile or damage geometry",
    "generationStatus": "succeeded",
    "artAcceptance": "pending actual in-game same-camera review; generation success is not art acceptance"
}
(SOURCE / "provenance.json").write_text(json.dumps(provenance, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
(OUTPUT / "source.json").write_text(json.dumps({"source": str(SOURCE.relative_to(ROOT)).replace("\\", "/"),
    "deriveScript": "tools/make-melee-material-v3.py", "artAcceptance": provenance["artAcceptance"]}, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
print(OUTPUT / "steel-ribbon.png")
