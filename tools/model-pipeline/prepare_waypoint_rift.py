"""Prepare a symmetric spatial rift and native scrolling-nebula metadata."""
from pathlib import Path
import hashlib,json,shutil,uuid
import numpy as np
from PIL import Image,ImageFilter,ImageOps

ROOT=Path(__file__).resolve().parents[2]
ART=ROOT/'source-art/maps/waypoints-rift-v7'
OUT=ROOT/'src/cocos/assets/resources/flat2d/waypoints-v1'
SOURCE=Path(r'C:/Users/Alexa/.codex/generated_images/01a1b873-5272-72a3-a18c-03223c658990/exec-a730df26-896e-4256-9c68-2a4e7d926259.png')

def mirror(image):
    left=image.crop((0,0,image.width//2,image.height))
    result=Image.new(image.mode,image.size)
    result.paste(left,(0,0));result.paste(ImageOps.mirror(left),(image.width//2,0))
    return result

def main():
    ART.mkdir(parents=True,exist_ok=True);OUT.mkdir(parents=True,exist_ok=True)
    shutil.copy2(SOURCE,ART/'spatial-rift-generated.png')
    image=mirror(Image.open(SOURCE).convert('RGBA'))
    p=np.asarray(image,dtype=np.float32);rgb=p[:,:,:3];value=rgb.max(2)
    # Retain the vivid original lip; the dark center is a separate animated mesh.
    a=p[:,:,3]*np.clip((value-65)/100,0,1)
    edge=Image.fromarray(np.dstack([rgb,a]).astype('uint8'))
    edge=mirror(edge.resize((512,768),Image.Resampling.LANCZOS))
    edge.save(OUT/'rift-edge-v7.png')
    glow=Image.new('RGBA',(256,384),(110,115,255,0))
    ga=edge.getchannel('A').resize((256,384),Image.Resampling.LANCZOS).filter(ImageFilter.GaussianBlur(7))
    glow.putalpha(ga);glow=mirror(glow);glow.save(OUT/'rift-glow-v7.png')
    # A clean dark interior patch, mirrored into a seamless tile; UVs are also
    # folded in the native lens, preserving bilateral motion at every time.
    patch=image.crop((300,620,500,820)).convert('RGB').resize((256,256),Image.Resampling.LANCZOS)
    tile=Image.new('RGB',(512,512));tile.paste(patch,(0,0));tile.paste(ImageOps.mirror(patch),(256,0));tile.paste(ImageOps.flip(patch),(0,256));tile.paste(ImageOps.flip(ImageOps.mirror(patch)),(256,256))
    tile.save(OUT/'rift-nebula-v7.png')
    widths=[]
    for i in range(33):
        row=round((1-i/32)*(image.height-1));candidates=[]
        for yy in range(max(0,row-7),min(image.height,row+8)):
            start=image.width//2+4
            row_rgb=rgb[yy,start:]
            score=(row_rgb[:,1]+row_rgb[:,2]*.5-row_rgb[:,0]*.8)*(p[yy,start:,3]/255)
            score=np.convolve(score,[.2,.6,.2],mode='same')
            index=int(np.argmax(score))
            if score[index]>65:candidates.append(max(.001,float(index+4-50)/image.width*2.1))
        widths.append(max(.001,min(.64,float(np.median(candidates)) if candidates else .001)))
    widths[0]=widths[-1]=.001
    # Smooth the measured cyan lip and keep the field inside its violet edge.
    widths=np.array(widths)
    smooth=widths.copy()
    for i in range(1,32):smooth[i]=(widths[i-1]+2*widths[i]+widths[i+1])/4
    widths=np.round(smooth,6).tolist()
    data="/** Generated by prepare_waypoint_rift.py; original OpenAI image_gen art. */\nexport const RIFT_ART={width:2.1,height:3,depth:.28,halfWidths:"+json.dumps(widths,separators=(',',':'))+"} as const;\n"
    (ROOT/'src/cocos/assets/scripts/features/portals/data/PortalRiftArt.ts').write_text(data,encoding='utf-8',newline='\n')
    outputs=[]
    template=json.loads((OUT/'waystone-rune-carved-v6.png.meta').read_text(encoding='utf-8'))
    for stem in ['rift-edge-v7','rift-glow-v7','rift-nebula-v7']:
        path=OUT/(stem+'.png');im=Image.open(path);pixels=np.asarray(im,dtype=np.int16)
        error=int(np.abs(pixels-pixels[:,::-1]).max());assert error==0
        outputs.append({'path':path.relative_to(ROOT).as_posix(),'size':list(im.size),'mode':im.mode,'sha256':hashlib.sha256(path.read_bytes()).hexdigest(),'horizontalMirrorMaxError':error})
        meta=path.with_suffix('.png.meta')
        if not meta.exists():
            old=template['uuid'];new=str(uuid.uuid5(uuid.NAMESPACE_URL,'singularity/rift-v7/'+stem))
            m=json.loads(json.dumps(template).replace(old,new).replace('waystone-rune-carved-v6',stem))
            if stem=='rift-nebula-v7':
                m['userData']['hasAlpha']=False
                for sub in m['subMetas'].values():
                    sub['userData']['wrapModeS']='repeat';sub['userData']['wrapModeT']='repeat'
            meta.write_text(json.dumps(m,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    review=Image.new('RGB',(512,768),'#32343d');review.paste(image.resize((512,768)),(0,0),image.resize((512,768)))
    review.save(ART/'rift-review.jpg',quality=94)
    (ART/'generation.json').write_text(json.dumps({'tool':'OpenAI image_gen built-in cloud','mode':'new original transparent VFX generation','userDirection':'blue-violet spatial rift, retaining bilateral symmetry','prompt':'prompt.txt','originalSource':str(SOURCE),'originalSha256':hashlib.sha256(SOURCE.read_bytes()).hexdigest(),'generationStatus':'succeeded','artAcceptance':'source sample reviewed; runtime pending','processing':'Pillow mirror, emission-lip alpha selection, soft glow, seamless nebula patch and per-row native lens profile','runtimeAnimation':'native mesh UV flow plus mirrored travelling highlights, not generated animation frames','outputs':outputs,'profileHalfWidths':widths},ensure_ascii=False,indent=2)+'\n',encoding='utf-8')

if __name__=='__main__':main()
